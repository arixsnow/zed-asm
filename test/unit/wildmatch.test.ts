test('a glob selects the files git sparse checkout selects', () => {
    for (const [glob, expected] of SELECTED) {
        const pattern = wildmatch(glob);
        assert.deepStrictEqual(
            PATHS.filter((path) => matchesPath([pattern], path)),
            expected,
            glob,
        );
    }
});

test('a glob git would abort on is rejected', () => {
    assertThrowsIncluding(() => wildmatch('br/[ab'), '"br/[ab" opens a [ it never closes');
    assertThrowsIncluding(() => wildmatch('br/[[:ab'), '"br/[[:ab" opens a [ it never closes');
    assertThrowsIncluding(() => wildmatch('x/[[:bogus:]]'), 'names the unknown class [:bogus:]');
    assertThrowsIncluding(() => wildmatch('x/[[::]]'), 'names the unknown class [::]');
});
